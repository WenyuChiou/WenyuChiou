#!/usr/bin/env node
/* Offline checks for the generated profile files. Zero dependencies; exits non-zero on the first failure. */
import assert from "node:assert/strict";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import content from "./profile-content.mjs";
import { render, validate, refresh, main } from "./build-profile.mjs";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const read = (rel) => fs.readFileSync(path.join(ROOT, rel), "utf8").replace(/\r\n/g, "\n");
const data = JSON.parse(read("scripts/profile-data.json"));
const rendered = render(data, content);
const locales = Object.values(content.locales);
const n = (v) => String(v).replace(/\B(?=(\d{3})+(?!\d))/g, ",");
let count = 0;
const ok = (name) => { count++; console.log(`ok - ${name}`); };
const attrs = (tag) => Object.fromEntries([...tag.matchAll(/([\w-]+)="([^"]*)"/g)].map((m) => [m[1], m[2]]));
const imgs = (md) => [...md.matchAll(/<img [^>]*>/g)].map((m) => attrs(m[0]));
const links = (md) => [...md.matchAll(/<a href="([^"]*)"/g)].map((m) => m[1]);
const unesc = (s) => s.replace(/&quot;/g, '"').replace(/&lt;/g, "<").replace(/&gt;/g, ">").replace(/&amp;/g, "&");

/* committed files */
assert.ok(rendered.size >= 50, `expected at least 50 files, got ${rendered.size}`);
for (const [rel, text] of rendered) assert.equal(read(rel), text, `${rel} is out of date: run node scripts/build-profile.mjs`);
ok("committed outputs equal render(committed data), for both locales");

const again = render(JSON.parse(JSON.stringify(data)), content);
for (const [rel, text] of rendered) { assert.equal(again.get(rel), text, rel); assert.ok(!text.includes("\r"), `${rel} has CR`); }
ok("output is deterministic and uses LF");

/* READMEs */
for (const L of locales) for (const i of imgs(read(L.readme))) if (!/^https?:/.test(i.src)) assert.ok(fs.existsSync(path.join(ROOT, i.src)), `${L.readme}: missing ${i.src}`);
ok("every local image a README references exists");

for (const L of locales) { const list = imgs(read(L.readme)); assert.ok(list.length >= 25); for (const i of list) assert.ok(i.alt && i.alt.trim(), `${L.readme}: no alt on ${i.src}`); }
ok("every <img> has a non-empty alt");

for (const L of locales) {
  const md = read(L.readme); let rows = 0;
  for (const block of md.match(/<p>\n[\s\S]*?\n<\/p>/g)) {
    let acc = 0;
    for (const line of block.split("\n")) {
      const ws = [...line.matchAll(/width="([\d.]+)%"/g)].map((m) => +m[1]);
      if (!ws.length) continue;
      assert.ok(!/<\/a>\s+<a /.test(line), `${L.readme}: whitespace between tiles of one row`);
      acc += ws.reduce((a, b) => a + b, 0);
      assert.ok(acc <= 100, `${L.readme}: row sums to ${acc}`);
      if (acc > 98) { acc = 0; rows++; }
    }
    assert.equal(acc, 0, `${L.readme}: a tile row sums to only ${acc}`);
  }
  assert.ok(rows === 8, `${L.readme}: ${rows} tile rows, expected 8`);
}
ok("each tile row's widths sum to at most 100 and more than 98");

for (const L of locales) {
  const md = read(L.readme);
  for (const bad of ["shields.io", "trophy", "dist/badge", "dist/summary", "AI Collaboration", "AI 協作", "#decision-provenance"]) assert.ok(!md.includes(bad), `${L.readme} contains ${bad}`);
  assert.ok(md.startsWith("<!-- Generated by scripts/build-profile.mjs"), `${L.readme} lacks the generated notice`);
}
ok("forbidden strings are absent and the generated notice is first");

for (const [rel, text] of rendered) {
  if (!rel.endsWith(".svg")) continue;
  assert.match(text, /<title>[^<]+<\/title>/, `${rel}: no title`);
  assert.ok(!/<script/i.test(text), `${rel}: script`);
  assert.ok(!/<foreignObject/i.test(text), `${rel}: foreignObject`);
  const urls = [...text.matchAll(/https?:\/\/[^\s"')<]+/g)].map((m) => m[0]).filter((u) => u !== "http://www.w3.org/2000/svg");
  assert.deepEqual(urls, [], `${rel}: external reference`);
  assert.ok(!/@import/.test(text), `${rel}: import`);
}
ok("SVGs have a title, no script, no foreignObject, no external reference");

{
  const [en, zh] = locales.map((L) => read(L.readme)), base = (s) => s.split("/").pop();
  assert.deepEqual(imgs(en).map((i) => base(i.src)), imgs(zh).map((i) => base(i.src)));
  /* every image has the same size in both languages; the two paper cards take half the row each */
  const research = (i) => /\/research-(wrr|floodabm)\.svg$/.test(i.src), sizes = (md) => imgs(md).map((i) => i.width || i.height);
  assert.deepEqual(sizes(en), sizes(zh));
  for (const md of [en, zh]) { const rw = imgs(md).filter(research).map((i) => parseFloat(i.width)); assert.equal(rw.length, 2); assert.ok(Math.min(...rw) >= 49 && rw[0] + rw[1] <= 100, `the paper cards do not split the row in half: ${rw}`); }
  assert.equal(links(en).length, links(zh).length);
  assert.ok(en.includes('<a href="README.zh-TW.md">繁體中文</a>') && zh.includes('<a href="README.md">English</a>'));
  assert.ok(links(zh).includes("https://wenyuchiou.github.io/zh/work/floodabm/") && links(zh).includes("https://wenyuchiou.github.io/assets/Wenyu_Chiou_Academic_CV_zh-TW.pdf"));
  assert.ok(links(en).includes("https://wenyuchiou.github.io/assets/Wenyu_Chiou_Academic_CV_EN.pdf") && links(en).includes("https://buymeacoffee.com/wenyuchiou"));
  assert.ok(zh.includes("hl=zh-TW") && en.includes("hl=en"));
  assert.ok(en.includes("standalone-portfolio/assets/commit-maps/activity-dam.svg") && en.includes("standalone-portfolio/assets/commit-maps/activity-snake.svg"));
  assert.ok(en.includes("https://wenyuchiou.github.io/#act5") && zh.includes("https://wenyuchiou.github.io/zh/#act5"));
  assert.ok(en.includes("https://www.threads.com/@wenyu_chiou") && zh.includes("https://www.threads.com/@wenyu_chiou"));
}
ok("EN and zh READMEs have the same images and links in the same order");

for (const L of locales) {
  const list = imgs(read(L.readme));
  const alt = (file) => { const i = list.find((x) => x.src.endsWith("/" + file)); assert.ok(i, `${L.readme}: no ${file}`); return unesc(i.alt); };
  for (const r of content.own) {
    const a = alt(`repo-${r.name}.svg`);
    assert.ok(a.endsWith(`${n(data.own[r.name])} stars.`) || a.endsWith(`星數 ${n(data.own[r.name])}。`), `${r.name}: ${a}`);
  }
  for (const u of content.upstream) {
    const a = alt(`pr-${u.repo.split("/")[1]}.svg`);
    assert.ok(a.startsWith(L.prAlt(u.repo, data.upstream[u.repo].mergedPrs, "")), `${u.repo}: ${a}`);
  }
}
ok("star and PR numbers in the alt text equal the data");

for (const L of locales) {
  const squash = (s) => s.replace(/&amp;/g, "&").replace(/&lt;/g, "<").replace(/\s+/g, "");
  const textOf = (rel) => squash([...rendered.get(rel).matchAll(/<text[^>]*>([^<]*)<\/text>/g)].map((m) => m[1]).join(""));
  const md = read(L.readme), dir = `assets/profile/${L.dir}/`;
  /* the background paragraph is plain text in the README, right before the research heading */
  assert.ok(md.includes(`<p>${L.bio.replace(/&/g, "&amp;")}</p>\n\n<h3>`), `${L.readme}: background paragraph missing`);
  /* three research directions, in order, each linking to its stage on the Research page and drawing its whole text */
  const row = imgs(md).filter((i) => /\/topic-/.test(i.src));
  assert.deepEqual(row.map((i) => i.src), content.topics.map((t) => `${dir}topic-${t.key}.svg`));
  content.topics.forEach((t, i) => {
    assert.ok(links(md).includes(`${L.research}#observatory-stage-${t.stage}`), `${L.readme}: no link to stage ${t.stage}`);
    const tx = textOf(`${dir}topic-${t.key}.svg`), loc = L.topics[i];
    for (const part of [loc.title, loc.q, loc.how]) assert.ok(tx.includes(squash(part)), `${L.dir} topic ${t.key}: "${part}" not drawn`);
    assert.equal(unesc(row[i].alt), loc.alt);
  });
  /* the two paper cards are slim: where the work stands, its question and an arrow, and no other text */
  for (const [file, r] of [["research-wrr.svg", L.wrr], ["research-floodabm.svg", L.abm]]) {
    assert.equal(textOf(`${dir}${file}`), squash(r.chip + r.q + "↗"), `${L.dir} ${file}: the card draws something other than its status and question`);
    assert.equal(unesc(imgs(md).find((i) => i.src.endsWith("/" + file)).alt), r.alt);
    assert.ok(r.alt.includes(r.chip) && r.alt.includes(r.q), `${L.dir} ${file}: the alt text misses the status or the question`);
    const height = +rendered.get(`${dir}${file}`).match(/viewBox="0 0 [\d.]+ ([\d.]+)"/)[1];
    assert.ok(height <= 180, `${L.dir} ${file}: the card is ${height} units tall, more than a slim card`);
  }
  /* the banner plays the loop: every step, caption and legend label is drawn, and motion is limited to people who allow it */
  const banner = rendered.get(`${dir}banner.svg`), bx = textOf(`${dir}banner.svg`);
  for (const part of [...L.loop.steps.map((x, i) => `${i + 1} ${x}`), ...L.loop.caps, ...Object.values(L.loop.legend), L.loop.note, L.loop.head, L.loop.year(1), L.loop.year(2), L.open, ...L.lead]) assert.ok(bx.includes(squash(part)), `${L.dir} banner: "${part}" not drawn`);
  for (const k of ["tide", "p1", "p2", "p3", "p4", "y1", "y2"]) assert.ok(banner.includes(`@keyframes ${k}{`), `${L.dir} banner: no ${k} keyframes`);
  /* no timeline steps backwards: a step out of order would silently replay an earlier state */
  const timelines = [...banner.matchAll(/@keyframes (\w+)\{((?:[^{}]*\{[^{}]*\})+)\}/g)];
  assert.ok(timelines.length >= 20, `${L.dir} banner: only ${timelines.length} timelines`);
  for (const [, name, body] of timelines) {
    const at = [...body.matchAll(/([\w.%,\s]+)\{/g)].flatMap((m) => m[1].split(",").map((x) => ({ from: 0, to: 100 })[x.trim()] ?? parseFloat(x)));
    assert.ok(at.every((v, i) => Number.isFinite(v) && v <= 100 && (!i || v >= at[i - 1])), `${L.dir} banner: timeline ${name} is out of order (${at.join(" ")})`);
  }
  for (const rel of [`${dir}banner.svg`, ...content.topics.map((t) => `${dir}topic-${t.key}.svg`)]) {
    const svg = rendered.get(rel), media = /@media \(prefers-reduced-motion:no-preference\)\{[\s\S]*?\}\}\n/;
    assert.ok(media.test(svg) && /animation:/.test(svg.match(media)[0]), `${rel}: no animation inside the motion query`);
    assert.ok(!/animation(-name|-duration)?:/.test(svg.replace(media, "")), `${rel}: an animation runs for people who turned motion off`);
  }
}
ok("the background paragraph, the three research directions and the banner's loop are all there");

for (const L of locales) {
  const zh = L.dir !== "en", squash = (s) => s.replace(/&amp;/g, "&").replace(/&lt;/g, "<").replace(/\s+/g, "");
  const textOf = (rel) => squash([...rendered.get(rel).matchAll(/<text[^>]*>([^<]*)<\/text>/g)].map((m) => m[1]).join(""));
  /* as in the approved concept, a small repo tile leaves its description to the alt text when it does not fit;
     the large tile and the two tiles of the second row always have the room, so three is the floor */
  let drawn = 0;
  content.own.forEach((r, i) => {
    const d = i === 0 ? (zh ? r.bigZh : r.bigEn) : zh ? r.zh : r.en, has = textOf(`assets/profile/${L.dir}/repo-${r.name}.svg`).includes(squash(d));
    if (i === 0) assert.ok(has, `${L.dir} ${r.name}: flagship description not drawn`);
    if (has) drawn++;
  });
  assert.ok(drawn >= 3, `${L.dir}: only ${drawn} repo tiles draw their description`);
  for (const u of content.upstream) assert.ok(textOf(`assets/profile/${L.dir}/pr-${u.repo.split("/")[1]}.svg`).includes(squash(zh ? u.zh : u.en)), `${L.dir} ${u.repo}: description not drawn`);
}
ok("the flagship, the larger repo tiles and every PR tile draw their whole description");

/* validate */
{
  const clone = () => JSON.parse(JSON.stringify(data));
  assert.doesNotThrow(() => validate(clone(), content));
  const cases = [
    (d) => { d.asOf = "2026-13-45"; }, (d) => { d.asOf = "12/11/2026"; }, (d) => { delete d.asOf; },
    (d) => { d.own["agent-board"] = 0; }, (d) => { d.own["agent-board"] = 1.5; }, (d) => { d.own["agent-board"] = "58"; }, (d) => { delete d.own["zotero-skills"]; },
    (d) => { d.upstream["morluto/rea"].mergedPrs = 0; }, (d) => { d.upstream["morluto/rea"].stars = -1; }, (d) => { d.upstream["NVIDIA/skills"].stars = NaN; },
    (d) => { delete d.upstream["punkpeye/awesome-mcp-servers"]; }, (d) => { d.ownForks["codex-delegate"] = -1; },
  ];
  cases.forEach((mutate, i) => { const d = clone(); mutate(d); assert.throws(() => validate(d, content), /profile data/, `case ${i} was accepted`); assert.throws(() => render(d, content), /profile data/, `render case ${i}`); });
}
ok("validate rejects bad data");

/* refresh and the CLI, with stub fetches */
const json = (body, okay = true) => ({ ok: okay, status: okay ? 200 : 500, json: async () => body });
const goodFetch = async (url) => (/search\/issues/.test(url) ? json({ total_count: 3, incomplete_results: false }) : json({ stargazers_count: 10, forks_count: 2 }));
const zeroPrs = async (u) => (/search\/issues/.test(u) ? json({ total_count: 0, incomplete_results: false }) : json({ stargazers_count: 5, forks_count: 0 }));
{
  const d = await refresh(goodFetch, "t", content, new Date("2026-01-02T03:04:05Z"));
  assert.equal(d.asOf, "2026-01-02"); assert.equal(d.upstream["morluto/rea"].mergedPrs, 3); assert.equal(d.own["agent-board"], 10);
}
ok("refresh returns valid data from a stub fetch");

await assert.rejects(refresh(async () => json({}, false), "t", content), /failed/);
await assert.rejects(refresh(async () => { throw new Error("offline"); }, "t", content), /offline/);
await assert.rejects(refresh(zeroPrs, "t", content), /merged PRs/);
await assert.rejects(refresh(async (u) => (/search\/issues/.test(u) ? json({ total_count: 2, incomplete_results: true }) : json({ stargazers_count: 5, forks_count: 0 })), "t", content), /incomplete/);
ok("refresh throws on a failed request, a bad number or an incomplete search");

for (const f of [async () => json({}, false), zeroPrs]) {
  const writes = [], errs = [];
  const code = await main(["--refresh"], { fetchImpl: f, token: "t", write: (r) => writes.push(r), read: () => { throw new Error("no read"); }, log: () => {}, err: (m) => errs.push(m) }, content);
  assert.equal(code, 1); assert.deepEqual(writes, []); assert.equal(errs.length, 1);
}
ok("the CLI exits 1 and writes no file when the refresh fails");

{
  const writes = new Map();
  const code = await main(["--refresh"], { fetchImpl: goodFetch, token: "t", write: (r, t) => writes.set(r, t), log: () => {}, err: () => {} }, content);
  assert.equal(code, 0); assert.ok(writes.has("scripts/profile-data.json") && writes.has("README.md") && writes.has("README.zh-TW.md")); assert.ok(writes.size >= 57);
}
ok("the CLI writes the data and every output after a good refresh");

console.log(`\n${count} checks passed`);
